"""Benchmark task registry (shared by run_benchmarks.py and report.py).

A task id resolves to one dict with the dataset, columns, recipe steps, metrics, model
and the protocol knobs the drivers take. Three sources, in order:

1. explicit entries in TASKS below (trees, forests, boosting, case weights, resampling
   schemes, tuning selection, workflow sets);
2. reference tasks from reference/tasks.json (their id; linear / logistic models);
3. scaling tasks `synth_<n>_<reg|clf>` on benchmarks/data (gitignored, generated by
   make_scaling_data.py).

`category` says what a ratio against R means: "framework-overhead" when both sides run
the same algorithm (lm vs the pivoted-QR port, glm vs the IRLS port, rpart vs its port,
xgboost vs its port), "workflow-level" otherwise (ranger vs the forest port, glmnet ridge
vs the native penalised IRLS when tuning logistic regression). `parity` names the
VERIFICATION.md phase that established numerical agreement for the model class.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REFERENCE_TASKS = {t["id"]: t for t in json.loads((ROOT / "reference" / "tasks.json").read_text())["tasks"]}

PARITY = {
    "linear_reg": "VERIFICATION.md Phase 4 / Phase 7 (L3/L4 pass)",
    "logistic_reg": "VERIFICATION.md Phase 4 / Phase 7 (L3/L4 pass)",
    "decision_tree": "VERIFICATION.md Phase 8d (rpart port, exact)",
    "rand_forest": "VERIFICATION.md Phase 8e (level 5, statistical)",
    "boost_tree": "VERIFICATION.md Phase 8f (xgboost port, exact to float32)",
}

SCALING_PREDICTORS = ["x1", "x2", "x3", "x4", "x5", "g"]
SCALING_STEPS = ["impute_median_numeric", "normalize_numeric", "dummy_nominal"]


def scaling(n: int, kind: str) -> dict:
    return {
        "dataset": str(ROOT / "benchmarks" / "data" / f"synth_{n}_{kind}.csv"),
        "outcome": "y",
        "type": "regression" if kind == "reg" else "classification",
        "predictors": SCALING_PREDICTORS,
        "steps": SCALING_STEPS,
        "metrics": ["rmse", "rsq"] if kind == "reg" else ["accuracy", "mn_log_loss"],
    }


def reference(task_id: str) -> dict:
    t = REFERENCE_TASKS[task_id]
    return {
        "dataset": str(ROOT / "reference" / "fixtures" / "datasets" / f"{t['dataset']}.csv"),
        "outcome": t["outcome"],
        "type": t["type"],
        "predictors": t["predictors"],
        "steps": t["steps"],
        "metrics": t["metrics"][:2],
    }


# explicit configurations: base spec + overrides
TASKS: dict[str, dict] = {
    # decision trees (rpart vs the rpart port): framework-overhead, incl. 20-point tuning + selection
    "ames_tree_reg": {**reference("ames_reg"), "model": "decision_tree", "select": True},
    "penguins_tree_clf": {**reference("penguins_clf"), "model": "decision_tree", "select": True},
    "synth_10000_tree_clf": {**scaling(10000, "clf"), "model": "decision_tree", "select": True},
    "synth_100000_tree_reg": {**scaling(100000, "reg"), "model": "decision_tree", "select": True},
    # random forests (ranger vs the ranger-rules port): workflow-level; no tuning
    "ames_rf_reg": {**reference("ames_reg"), "model": "rand_forest", "model_args": {"trees": 200}, "tune": "none"},
    "synth_10000_rf_clf": {**scaling(10000, "clf"), "model": "rand_forest", "model_args": {"trees": 200}, "tune": "none"},
    # boosted trees (xgboost vs the hist port): framework-overhead, incl. 20-point tuning + selection
    "ames_xgb_reg": {**reference("ames_reg"), "model": "boost_tree", "model_args": {"trees": 50}, "select": True},
    "synth_10000_xgb_clf": {**scaling(10000, "clf"), "model": "boost_tree", "model_args": {"trees": 50}, "select": True},
    "synth_100000_xgb_clf": {**scaling(100000, "clf"), "model": "boost_tree", "model_args": {"trees": 50}, "tune": "none"},
    # case weights (frequency weights through recipe, model and metrics)
    "synth_10000_reg_wfreq": {**scaling(10000, "reg"), "case_weights": "w:frequency", "tune": "none"},
    "synth_10000_clf_wfreq": {**scaling(10000, "clf"), "case_weights": "w:frequency", "tune": "none"},
    # resampling schemes
    "synth_10000_reg_boot": {**scaling(10000, "reg"), "resampling": "bootstraps", "times": 25, "tune": "none"},
    "synth_10000_reg_repcv": {**scaling(10000, "reg"), "resampling": "repeated", "repeats": 3, "tune": "none"},
    "synth_10000_clf_boot": {**scaling(10000, "clf"), "resampling": "bootstraps", "times": 25, "tune": "none"},
    # workflow sets (base model + tuned tree + xgboost on one set of folds)
    "synth_10000_reg_wfs": {**scaling(10000, "reg"), "wfs": True, "tune": "none"},
    "penguins_clf_wfs": {**reference("penguins_clf"), "wfs": True, "tune": "none"},
    "ames_reg_wfs": {**reference("ames_reg"), "wfs": True, "tune": "none"},
    # 1e6-row scaling point: CV only (a 20-point glmnet grid at 1e6 rows exceeds the trial timeout in R)
    "synth_1000000_reg": {**scaling(1_000_000, "reg"), "tune": "none"},
    "synth_1000000_clf": {**scaling(1_000_000, "clf"), "tune": "none"},
}


def task_spec(task_id: str) -> dict:
    if task_id in TASKS:
        spec = dict(TASKS[task_id])
    elif task_id in REFERENCE_TASKS:
        spec = reference(task_id)
    elif task_id.startswith("synth_"):
        parts = task_id.split("_")
        spec = scaling(int(parts[1]), parts[2] if len(parts) > 2 else "reg")
    else:
        raise SystemExit(f"unknown task {task_id}")
    spec.setdefault("model", "linear_reg" if spec["type"] == "regression" else "logistic_reg")
    spec.setdefault("model_args", {})
    spec.setdefault("case_weights", None)
    spec.setdefault("resampling", "vfold")
    spec.setdefault("repeats", 1)
    spec.setdefault("times", 25)
    spec.setdefault("tune", "grid" if spec["model"] in ("logistic_reg", "decision_tree", "boost_tree") else "none")
    spec.setdefault("select", False)
    spec.setdefault("wfs", False)
    spec["id"] = task_id
    spec["r_engine"] = {"linear_reg": "lm", "logistic_reg": "glm", "decision_tree": "rpart",
                        "rand_forest": "ranger", "boost_tree": "xgboost"}[spec["model"]]
    spec["parity"] = PARITY[spec["model"]]
    return spec


def category(spec: dict, engine: str) -> str:
    """What a ratio against R means for this task and candidate engine."""
    if engine in ("linfa", "smartcore"):
        return "workflow-level (backend solver vs R's)"
    if spec["model"] == "rand_forest":
        return "workflow-level (ranger vs forest port, different RNG)"
    if spec["model"] == "logistic_reg" and spec["tune"] == "grid":
        return "framework-overhead (glm vs IRLS port); tune: workflow-level (glmnet ridge vs penalised IRLS)"
    return {
        "linear_reg": "framework-overhead (lm vs pivoted-QR port)",
        "logistic_reg": "framework-overhead (glm vs IRLS port)",
        "decision_tree": "framework-overhead (rpart vs rpart port)",
        "boost_tree": "framework-overhead (xgboost vs hist port)",
    }[spec["model"]]


def driver_flags(spec: dict, threads: int, warm: int, v: int, tune_levels: int) -> list[str]:
    flags = [
        "--dataset", spec["dataset"], "--outcome", spec["outcome"], "--type", spec["type"],
        "--predictors", ",".join(spec["predictors"]), "--steps", ",".join(spec["steps"]),
        "--metrics", ",".join(spec["metrics"]), "--threads", str(threads), "--warm", str(warm),
        "--model", spec["model"], "--resampling", spec["resampling"], "--v", str(v),
        "--repeats", str(spec["repeats"]), "--times", str(spec["times"]),
        "--tune", spec["tune"], "--tune-levels", str(tune_levels),
    ]
    if spec["model_args"]:
        flags += ["--model-args", ",".join(f"{k}={v}" for k, v in spec["model_args"].items())]
    if spec["case_weights"]:
        flags += ["--case-weights", spec["case_weights"]]
    if spec["select"]:
        flags.append("--select")
    if spec["wfs"]:
        flags.append("--wfs")
    return flags
